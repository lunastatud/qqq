# 3. ПОЯСНЕНИЯ ДЛЯ МЕНЮ
# ==========================================
EVENT_EXPLANATIONS = {
    Event.X0: "Имитация нажатия физической кнопки на корпусе (старт в незнакомой среде)",
    Event.X1: "Имитация успешного подключения к домашней Wi-Fi сети",
    Event.X2: "Имитация нажатия кнопки «Старт» в приложении / голосом / по расписанию",
    Event.X3: "Имитация нажатия кнопки «Стоп» в приложении",
    Event.X4: "Имитация падения заряда батареи до 15% и ниже",
    Event.X5: "Имитация физического контакта с контактами док-станции",
    Event.X6: "Имитация критической ошибки (щетка заблокирована, робот застрял, подъем)",
    Event.X7: "Имитация действий пользователя: очистка щетки и нажатие «Сброс»",
    Event.X8: "Имитация команды «Найти робот» из приложения",
    Event.X9: "Имитация срабатывания бампера / датчика виртуальной стены",
}

# ==========================================
# 4. КЛАСС РОБОТА С FSM (ИСПРАВЛЕННЫЙ)
# ==========================================
class RobotFSM:
    def __init__(self):
        self.state = State.S0

    def trigger(self, event):
        if event in FSM[self.state]:
            action, next_state = FSM[self.state][event]
            print(f"\n⚡ Событие: {event}")
            print(f"▶️  Действие: {action}")

            if next_state != self.state:
                print(f"🔄 Переход: {self.state} ➡️ {next_state}")
                self.state = next_state
            else:
                # Явное объяснение, почему состояние не изменилось
                if event == Event.X9:
                    print(f"⏳ Робот объехал препятствие и ПРОДОЛЖИЛ уборку (остается в {self.state})")
                elif event == Event.X3:
                    print(f"⏳ Команда «Стоп» подтверждена, робот остается в режиме простоя ({self.state})")
                elif event == Event.X8:
                    print(f"⏳ Сигнал поиска отправлен, робот остается в режиме простоя ({self.state})")
                else:
                    print(f"⏳ Действие выполнено, робот остается в состоянии {self.state}")
            return True
        else:
            print(f"❌ Событие {event} сейчас недоступно в состоянии {self.state}!")
            return False

    def run_interactive(self):
        print("=" * 70)
        print(" ИНТЕРАКТИВНЫЙ РЕЖИМ: ПОЛНАЯ ВЕРСИЯ FSM (все события)")
        print(" (Все переходы исправлены и соответствуют документации)")
        print("=" * 70)

        while True:
            print(f"\n[ТЕКУЩЕЕ СОСТОЯНИЕ]: {self.state}")
            print("-" * 70)

            available_events = list(FSM[self.state].keys())

            print("📋 ДОСТУПНЫЕ ДЕЙСТВИЯ:")
            for i, event in enumerate(available_events, 1):
                explanation = EVENT_EXPLANATIONS.get(event, "")
                print(f"  {i}. [{event}] — {explanation}")
            print("  0. Выход из программы")

            try:
                choice = input("\n➤ Введите номер ИЛИ код события (например, X2): ").strip().upper()
            except EOFError:
                print("\n[Ввод прерван средой. Завершение работы.]")
                break
            except KeyboardInterrupt:
                print("\n[Прервано пользователем. Завершение работы.]")
                break

            if choice == '0':
                print("Завершение работы. До свидания!")
                break

            selected_event = None

            if choice.isdigit():
                idx = int(choice) - 1
                if 0 <= idx < len(available_events):
                    selected_event = available_events[idx]
                else:
                    print("⚠️ Неверный номер, попробуйте снова.")
            elif choice in available_events:
                selected_event = choice
            else:
                print("⚠️ Неверный ввод. Введите номер из списка или точный код события (X0–X9).")

            if selected_event:
                self.trigger(selected_event)


if __name__ == "__main__":
    robot = RobotFSM()
    robot.run_interactive()