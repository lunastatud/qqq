# ==========================================
# 1. СОСТОЯНИЯ, СОБЫТИЯ, ДЕЙСТВИЯ
# ==========================================
class State:
    S0 = "S0: Инициализация и построение карты"
    S1 = "S1: Ожидание / Простой (Idle)"
    S2 = "S2: Активная уборка и навигация"
    S3 = "S3: Возврат на базу и зарядка"
    S4 = "S4: Ошибка / Аварийная остановка"

class Event:
    X0 = "X0: Нажатие кнопки / Физический старт в незнакомой среде"
    X1 = "X1: Успешное подключение к Wi-Fi / Синхронизация с облаком"
    X2 = "X2: Команда «Старт» (из приложения, голосом или по расписанию)"
    X3 = "X3: Команда «Стоп» / Успешное завершение уборки"
    X4 = "X4: Уровень заряда батареи ≤ 15%"
    X5 = "X5: Физический контакт с зарядной станцией (Док-станция найдена)"
    X6 = "X6: Критическая ошибка (блокировка щетки, застревание, подъем)"
    X7 = "X7: Сброс ошибки пользователем"
    X8 = "X8: Команда «Поиск устройства»"
    X9 = "X9: Срабатывание датчика препятствия / виртуальной стены"

class Action:
    Y0 = "Y0: Физический сигнал (писк) / Включение BLE-модуля"
    Y1 = "Y1: Голос «Подключение выполнено» / Отправка MAC-адреса в облако"
    Y2 = "Y2: Голос «Начинаю уборку» / Запуск моторов (турбина, щетки)"
    Y3 = "Y3: Движение по алгоритму A* / Корректировка траектории (обход)"
    Y4 = "Y4: Голос «Низкий заряд, возвращаюсь» / Построение пути к базе"
    Y5 = "Y5: Отключение ходовых моторов / Начало зарядки / Отправка телеметрии"
    Y6 = "Y6: Аварийная остановка моторов / Мелодия ошибки / Тихое мигание LED / Push-уведомление"
    Y7 = "Y7: Громкий непрерывный звуковой сигнал (15–20 сек)"
    Y8 = "Y8: Пауза движения / Голосовой запрос в приложение «Сохранить новую карту?»"
    Y9 = "Y9: Отключение голосовых оповещений / Начало зарядки / Отправка телеметрии"

# ==========================================
# 2. ИСПРАВЛЕННАЯ ТАБЛИЦА ПЕРЕХОДОВ FSM
# ==========================================
FSM = {
    State.S0: {
        Event.X0: (Action.Y8, State.S1),  # Сценарий 9: Старт в незнакомой среде → S1
        Event.X1: (Action.Y1, State.S1),  # Сценарий 1: Подключение к Wi-Fi → S1
    },
    State.S1: {
        Event.X0: (Action.Y0, State.S0),  # Возврат к инициализации → S0
        Event.X2: (Action.Y2, State.S2),  # Сценарии 2,5,8: Старт уборки → S2
        Event.X3: (Action.Y5, State.S1),  # Стоп в простое: отключение моторов → остается в S1
        Event.X8: (Action.Y7, State.S1),  # Сценарий 7: Поиск устройства → остается в S1
    },
    State.S2: {
        Event.X9: (Action.Y3, State.S2),  # Сценарий 4: Препятствие → остается в S2 (обход)
        Event.X4: (Action.Y4, State.S3),  # Сценарий 3: Низкий заряд → S3
        Event.X5: (Action.Y5, State.S1),  # База найдена во время уборки → S1
        Event.X3: (Action.Y9, State.S1),  # Сценарий 10: Стоп во время уборки → S1
        Event.X6: (Action.Y6, State.S4),  # Сценарий 6: Критическая ошибка → S4
    },
    State.S3: {
        Event.X5: (Action.Y5, State.S2),  # Сценарий 3: Стыковка с базой → S2 (продолжение уборки)
    },
    State.S4: {
        Event.X7: (Action.Y1, State.S1),  # Сценарий 6: Сброс ошибки → S1
    },
}

